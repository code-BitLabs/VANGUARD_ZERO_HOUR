import { z } from 'zod';
import { DifficultySchema } from './common.schema';

export const EnemyAwarenessStateSchema = z.enum([
  'UNAWARE',
  'SUSPICIOUS',
  'INVESTIGATING',
  'ALERTED',
  'ENGAGING',
  'SUPPRESSING',
  'SEARCHING',
  'REPOSITIONING',
  'RETREATING',
  'DEAD',
]);
export type EnemyAwarenessState = z.infer<typeof EnemyAwarenessStateSchema>;

export const CombatDomainSchema = z.enum(['ground', 'air', 'vehicle']);
export type CombatDomain = z.infer<typeof CombatDomainSchema>;

export const EnemyWeaponClassSchema = z.enum([
  'enemy_assault_rifle',
  'enemy_smg',
  'enemy_shotgun',
  'enemy_sniper',
  'enemy_lmg',
  'enemy_autocannon',
  'enemy_rocket',
]);
export type EnemyWeaponClass = z.infer<typeof EnemyWeaponClassSchema>;

export const PlayerHitZoneSchema = z.enum(['head', 'upper_torso', 'lower_body', 'splash']);
export type PlayerHitZone = z.infer<typeof PlayerHitZoneSchema>;

export const DifficultyCombatProfileSchema = z.object({
  difficulty: DifficultySchema,
  maxGlobalAttackers: z.number().int().min(1).max(8),
  maxSquadAttackers: z.number().int().min(1).max(8),
  maxGlobalHeavyAttackers: z.number().int().min(1).max(4),
  maxSquadSuppressors: z.number().int().min(1).max(4),
  maxGlobalSuppressors: z.number().int().min(1).max(4),
  reactionDelayBaseSec: z.number().min(0.1).max(3.0),
  reactionDelayJitterSec: z.number().min(0).max(1.5),
  spreadMultiplier: z.number().min(0.2).max(3.0),
  burstPauseMultiplier: z.number().min(0.3).max(3.0),
  damageMultiplier: z.number().min(0.2).max(3.0),
  damageBurstThreshold2s: z.number().min(15).max(200),
  airInitialGraceSec: z.number().min(0.5).max(15),
  groundInitialGraceSec: z.number().min(0.2).max(10),
});
export type DifficultyCombatProfile = z.infer<typeof DifficultyCombatProfileSchema>;

export const EnemyWeaponProfileSchema = z.object({
  weaponClass: EnemyWeaponClassSchema,
  displayName: z.string(),
  roundsPerBurstMin: z.number().int().min(1),
  roundsPerBurstMax: z.number().int().min(1),
  shotIntervalSec: z.number().positive(),
  burstCooldownMinSec: z.number().positive(),
  burstCooldownMaxSec: z.number().positive(),
  baseSpreadRad: z.number().nonnegative(),
  recoilBloomPerShotRad: z.number().nonnegative(),
  pelletCount: z.number().int().min(1).default(1),
  magazineSize: z.number().int().min(1),
  reloadDurationSec: z.number().positive(),
  effectiveRangeMeters: z.number().positive(),
  maxRangeMeters: z.number().positive(),
  baseDamage: z.number().positive(),
  headshotMultiplier: z.number().min(1).default(1.2),
  isProjectile: z.boolean().default(false),
});
export type EnemyWeaponProfile = z.infer<typeof EnemyWeaponProfileSchema>;

