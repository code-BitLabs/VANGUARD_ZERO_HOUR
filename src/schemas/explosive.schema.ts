import { z } from 'zod';

export const ExplosiveIdSchema = z.enum([
  'hand_grenade',
  'grenade_shell',
  'rocket',
  'guided_missile',
  'enemy_rocket',
  'enemy_grenade',
  'c4_charge',
  'standard_aerial_bomb',
  'heavy_explosive_bomb',
  'precision_guided_bomb',
  'cluster_munition_bomb',
  'cluster_submunition',
  'strategic_nuclear_weapon',
]);
export type ExplosiveId = z.infer<typeof ExplosiveIdSchema>;

export const ExplosiveCategorySchema = z.enum([
  'thrown',
  'launcher',
  'placed_c4',
  'conventional_bomb',
  'strategic_nuclear',
]);
export type ExplosiveCategory = z.infer<typeof ExplosiveCategorySchema>;

export const ConventionalBombIdSchema = z.enum([
  'standard_aerial_bomb',
  'heavy_explosive_bomb',
  'precision_guided_bomb',
  'cluster_munition_bomb',
]);
export type ConventionalBombId = z.infer<typeof ConventionalBombIdSchema>;

export const ExplosiveKinematicsSchema = z.object({
  initialSpeed: z.number().nonnegative(),
  acceleration: z.number().nonnegative(),
  boostDurationSec: z.number().nonnegative(),
  maxSpeed: z.number().nonnegative(),
  gravityScale: z.number().nonnegative(),
  drag: z.number().nonnegative(),
  maxTurnRateDegPerSec: z.number().nonnegative(),
  restitution: z.number().min(0).max(1),
  friction: z.number().min(0).max(1),
  collisionRadius: z.number().positive(),
});

export const ExplosiveDetonationSchema = z.object({
  triggerMode: z.enum(['fuse', 'impact', 'remote', 'altitude_split', 'shockwave']),
  fuseTimeSec: z.number().nonnegative(),
  maxLifetimeSec: z.number().positive(),
  armingDelaySec: z.number().nonnegative(),
  splitAltitudeMeters: z.number().nonnegative().default(0),
  submunitionCount: z.number().int().nonnegative().default(0),
});

export const ExplosiveBlastSchema = z.object({
  maxDamage: z.number().nonnegative(),
  armorPenetration: z.number().min(0).max(1),
  innerRadius: z.number().nonnegative(),
  outerRadius: z.number().positive(),
  falloffExponent: z.number().positive(),
  vehicleDamageMultiplier: z.number().positive(),
  destructionPower: z.number().positive(),
  cameraShakeIntensity: z.number().nonnegative(),
  suppressionRadius: z.number().nonnegative(),
});

export const ExplosiveProfileSchema = z.object({
  id: ExplosiveIdSchema,
  name: z.string().min(1),
  shortName: z.string().min(1),
  category: ExplosiveCategorySchema,
  requisitionCost: z.number().int().nonnegative().default(0),
  cooldownSec: z.number().nonnegative().default(0),
  kinematics: ExplosiveKinematicsSchema,
  detonation: ExplosiveDetonationSchema,
  blast: ExplosiveBlastSchema,
});
export type ExplosiveProfile = z.infer<typeof ExplosiveProfileSchema>;

