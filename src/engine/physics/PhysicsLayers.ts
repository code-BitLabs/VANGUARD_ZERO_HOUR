const LAYER_LABELS: Array<[number, string]> = [
  [COLLISION_LAYER.WORLD, 'WORLD'],
  [COLLISION_LAYER.COVER, 'COVER'],
  [COLLISION_LAYER.DESTRUCTIBLE, 'DESTRUCTIBLE'],
  [COLLISION_LAYER.ENEMY, 'ENEMY'],
  [COLLISION_LAYER.VEHICLE, 'VEHICLE'],
  [COLLISION_LAYER.PLAYER, 'PLAYER'],
  [COLLISION_LAYER.PROJECTILE, 'PROJECTILE'],
  [COLLISION_LAYER.WINDOW_SILL, 'WINDOW_SILL'],
  [COLLISION_LAYER.TRIGGER, 'TRIGGER'],
];

export function formatCollisionLayer(layer: number): string {
  const names: string[] = [];
  for (let i = 0; i < LAYER_LABELS.length; i++) {
    const [bit, label] = LAYER_LABELS[i];
    if ((layer & bit) !== 0) {
      names.push(label);
    }
  }
  return names.length > 0 ? names.join('|') : `0x${layer.toString(16)}`;
}
